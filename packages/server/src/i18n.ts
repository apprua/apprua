const DICTS: Record<Lang, Dict> = { en, it };

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k === 'brand' && vars.brand === undefined ? config.brand : String(vars[k] ?? `{${k}}`)));
}

/** Translates a message that may be a key (e.g. "err.password_short") or plain text. */
export const tMsg = (lang: Lang, msg: string) => (/^err\.[a-z_]+$/.test(msg) ? t(lang, msg) : msg);

/** ?lang= (remembered in a cookie) > cookie > browser language > DEFAULT_LANG. */
export function langOf(req: FastifyRequest): Lang {
  const q = (req.query as Record<string, string> | undefined)?.lang;
  if (q && LANGS.includes(q as Lang)) return q as Lang;
  const c = /(?:^|;\s*)apprua_lang=(\w+)/.exec(String(req.headers.cookie ?? ''))?.[1];
  if (c && LANGS.includes(c as Lang)) return c as Lang;
  const al = String(req.headers['accept-language'] ?? '').toLowerCase();
  for (const part of al.split(',')) {
    const code = part.trim().slice(0, 2) as Lang;
    if (LANGS.includes(code)) return code;
  }
  return config.defaultLang;
}

export function checkDictionaries(): string[] {
  const missing: string[] = [];
  for (const k of Object.keys(en)) if (!(k in it)) missing.push(`it:${k}`);
  for (const k of Object.keys(it)) if (!(k in en)) missing.push(`en:${k}`);
  return missing;
}
